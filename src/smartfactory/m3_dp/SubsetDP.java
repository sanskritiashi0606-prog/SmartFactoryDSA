package smartfactory.m3_dp;

import java.util.ArrayList;
import java.util.List;

/**
 * Subset Dynamic Programming for Production Resource Allocation.
 * Domain Use Case: Balances workload partitions between parallel manufacturing lines,
 * determines exact batch lot fulfillment, and solves resource-constrained knapsack decisions.
 */
public class SubsetDP {

    public static class KnapsackResult {
        public final int maxYield;
        public final List<Integer> selectedItemIndices;

        public KnapsackResult(int maxYield, List<Integer> selectedItemIndices) {
            this.maxYield = maxYield;
            this.selectedItemIndices = selectedItemIndices;
        }
    }

    /**
     * Determines if a set of machine workloads can be partitioned equally between two parallel lines.
     *
     * Time Complexity: O(N * S) where N is number of machines and S is total sum of workloads.
     * Space Complexity: O(S) pseudo-polynomial space.
     *
     * @param workloads Array of hourly machine workloads
     * @return true if an exact 50-50 line split is possible, false otherwise
     */
    public static boolean canPartitionWorkloadEqually(int[] workloads) {
        if (workloads == null || workloads.length < 2) return false;
        int totalSum = 0;
        for (int w : workloads) totalSum += w;

        if (totalSum % 2 != 0) return false;
        int target = totalSum / 2;

        boolean[] dp = new boolean[target + 1];
        dp[0] = true;

        for (int load : workloads) {
            for (int j = target; j >= load; j--) {
                dp[j] = dp[j] || dp[j - load];
            }
        }
        return dp[target];
    }

    /**
     * 0/1 Knapsack optimization to maximize total production yield/revenue under a maximum
     * machine hours budget or energy limit.
     *
     * Time Complexity: O(N * C) where N is number of orders and C is budget capacity.
     * Space Complexity: O(N * C) allowing item selection backtracking.
     *
     * @param yields Production value/profit generated by each job
     * @param hoursRequired Machine hours consumed by each job
     * @param maxAvailableHours Total allowable factory operating hours
     * @return KnapsackResult containing maximum profit and selected order indices
     */
    public static KnapsackResult optimizeResourceAllocation(int[] yields, int[] hoursRequired, int maxAvailableHours) {
        if (yields == null || hoursRequired == null || maxAvailableHours <= 0) {
            return new KnapsackResult(0, new ArrayList<>());
        }
        int n = yields.length;
        int[][] dp = new int[n + 1][maxAvailableHours + 1];

        for (int i = 1; i <= n; i++) {
            int y = yields[i - 1];
            int h = hoursRequired[i - 1];
            for (int w = 0; w <= maxAvailableHours; w++) {
                if (h <= w) {
                    dp[i][w] = Math.max(dp[i - 1][w], dp[i - 1][w - h] + y);
                } else {
                    dp[i][w] = dp[i - 1][w];
                }
            }
        }

        // Backtrack to find chosen items
        List<Integer> chosen = new ArrayList<>();
        int remHours = maxAvailableHours;
        for (int i = n; i >= 1; i--) {
            if (dp[i][remHours] != dp[i - 1][remHours]) {
                chosen.add(i - 1);
                remHours -= hoursRequired[i - 1];
            }
        }

        return new KnapsackResult(dp[n][maxAvailableHours], chosen);
    }

    /**
     * Checks if exact target inventory quantity can be assembled from available pre-packaged bins.
     *
     * Time Complexity: O(N * Target).
     * Space Complexity: O(Target).
     *
     * @param binSizes Sizes of raw material bin packages
     * @param targetQuantity Exact units needed for the order
     * @return true if exact combination exists, false otherwise
     */
    public static boolean canFulfillExactBatch(int[] binSizes, int targetQuantity) {
        if (binSizes == null || targetQuantity < 0) return false;
        boolean[] dp = new boolean[targetQuantity + 1];
        dp[0] = true;

        for (int bin : binSizes) {
            for (int q = targetQuantity; q >= bin; q--) {
                dp[q] = dp[q] || dp[q - bin];
            }
        }
        return dp[targetQuantity];
    }
}
